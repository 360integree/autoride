class TemplaticaUser
{
    /**************************************************************************/
    
    function __construct()
    {
        
    }
    
	/**************************************************************************/
	
	function getUserRoleDictionary()
	{
        $data=array();
        
        $role=get_editable_roles();
        
        foreach($role as $index=>$value)
            $data[$index]=array($value['name']);
        
        return($data);
	}
    
    /**************************************************************************/
}

