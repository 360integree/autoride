class TemplaticaValidation
{
	/**************************************************************************/

	static function isEmpty($value)
	{
		return(strlen(trim(strval($value))) ? false : true);
	}
	
	/**************************************************************************/

	static function isNotEmpty($value)
	{
		return(!self::isEmpty($value));
	}
	
	/**************************************************************************/
}

